    logFile = config.file
    if logFile then
        -- Ensure log directory exists
        local Executor = TempleExRequire("executor")
        local dir = logFile:match("^(.+)[/\\][^/\\]+$")
        if dir then
            pcall(Executor.fs_mkdir, dir)
        end
    end
end

