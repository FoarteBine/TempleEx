local REQUIRED_PALETTE = {
    "bg-0", "bg-1", "bg-2", "fg-0", "fg-1", "accent", "accent-2", "danger", "success", "warning"
}

-- Convert hex color to Color3
local function hexToColor3(hex)
    hex = hex:gsub("#", "")
    if #hex == 3 then
        hex = hex:gsub("(.)", "%1%1")
    end
    local r = tonumber(hex:sub(1, 2), 16) / 255
    local g = tonumber(hex:sub(3, 4), 16) / 255
    local b = tonumber(hex:sub(5, 6), 16) / 255
    return Color3.new(r, g, b)
end

-- Resolve palette reference (e.g., "palette.accent" -> actual Color3)
local function resolvePaletteRef(ref, palette)
    if type(ref) ~= "string" then return ref end
    local key = ref:match("^palette%.(.+)$")
    if key and palette[key] then
        return palette[key]
    end
    -- Maybe it's a direct hex
    if ref:sub(1,1) == "#" then
        return hexToColor3(ref)
    end
    return ref
end

-- Deep clone table
local function deepClone(t)
    if type(t) ~= "table" then return t end
    local copy = {}
    for k, v in pairs(t) do
        copy[k] = deepClone(v)
    end
    return copy
end

-- Merge theme with base (extends)
function ThemeEngine.mergeTheme(base, override)
    local result = deepClone(base)
    for k, v in pairs(override) do
        if type(v) == "table" and type(result[k]) == "table" and not ThemeEngine.isArray(v) then
            result[k] = ThemeEngine.mergeTheme(result[k], v)
        else
            result[k] = v
        end
    end
    return result
end

function ThemeEngine.isArray(t)
    if type(t) ~= "table" then return false end
    local count = 0
    for k, _ in pairs(t) do
        if type(k) == "number" and k > 0 then count = count + 1 else return false end
    end
    return count > 0 and count == #t
end

-- Load a single theme file
function ThemeEngine.loadTheme(name, themesPath)
    local path = themesPath .. "/" .. name .. ".yaml"
    local ok, content = Executor.fs_read(path)
    if not ok or not content then
        return nil, "Failed to read theme file: " .. path
    end

    local theme, errors = YAML.parse(content)
    if errors and #errors > 0 then
        return nil, "YAML parse errors: " .. table.concat(errors, "; ")
    end

    if not theme or theme.temple_theme ~= 1 then
        return nil, "Invalid theme format (missing temple_theme: 1)"
    end

    -- Handle extends
    if theme.extends then
        local baseTheme = ThemeEngine.themes[theme.extends]
        if not baseTheme then
            -- Try to load base
            local base, err = ThemeEngine.loadTheme(theme.extends, themesPath)
            if not base then
                return nil, "Base theme '" .. theme.extends .. "' not found: " .. err
            end
            baseTheme = base
        end
        theme = ThemeEngine.mergeTheme(baseTheme, theme)
    end

    -- Validate required tokens
    theme.tokens = theme.tokens or {}
    theme.palette = theme.palette or {}
    local missingTokens = {}
    for _, token in ipairs(REQUIRED_TOKENS) do
        if not theme.tokens[token] then
            table.insert(missingTokens, token)
        end
    end
    if #missingTokens > 0 then
        Log.warn("Theme '" .. name .. "' missing tokens: " .. table.concat(missingTokens, ", "))
    end

    -- Validate palette
    local missingPalette = {}
    for _, p in ipairs(REQUIRED_PALETTE) do
        if not theme.palette[p] then
            table.insert(missingPalette, p)
        end
    end
    if #missingPalette > 0 then
        return nil, "Theme missing palette colors: " .. table.concat(missingPalette, ", ")
    end

    theme.slug = name
    theme.displayName = theme.name or name
    return theme
end

-- Load all themes from directory
function ThemeEngine.loadAllThemes(themesPath)
    ThemeEngine.themes = {}
    local ok, files = Executor.fs_list(themesPath)
    if not ok or not files then
        Log.warn("Could not list themes directory:", themesPath)
        return
    end

    for _, file in ipairs(files) do
        -- Extract basename without path and extension (handles / and \ separators)
        local name = file:match("([^/\\]+)%.yaml$")
        if name then
            local theme, err = ThemeEngine.loadTheme(name, themesPath)
            if theme then
                ThemeEngine.themes[name] = theme
                Log.info("Loaded theme:", name)
            else
                Log.warn("Failed to load theme '" .. name .. "': " .. err)
            end
        end
    end
end

-- Apply theme (resolve tokens to actual values)
function ThemeEngine.applyTheme(name)
    local theme = ThemeEngine.themes[name]
    if not theme then
        return false, "Theme not found: " .. name
    end

    -- Resolve palette
    local resolvedPalette = {}
    for k, v in pairs(theme.palette) do
        resolvedPalette[k] = hexToColor3(v)
    end
    ThemeEngine.palette = resolvedPalette

    -- Resolve tokens
    local resolvedTokens = {}
    for token, ref in pairs(theme.tokens) do
        resolvedTokens[token] = resolvePaletteRef(ref, resolvedPalette)
    end

    -- Apply accent override from config
    local config = Config.data
    if config and config.theme.accent_override then
        local override = config.theme.accent_override
        if override:sub(1,1) == "#" then
            resolvedTokens["text.accent"] = hexToColor3(override)
            resolvedTokens["toggle.track.on"] = hexToColor3(override)
            resolvedTokens["button.primary.bg"] = hexToColor3(override)
            resolvedTokens["tab.active"] = hexToColor3(override)
            resolvedTokens["slider.fill"] = hexToColor3(override)
            resolvedTokens["dock.icon.active"] = hexToColor3(override)
            resolvedTokens["snap.preview"] = hexToColor3(override)
            resolvedTokens["workspace.active.fg"] = hexToColor3(override)
        end
    end

    ThemeEngine.tokens = resolvedTokens
    ThemeEngine.currentTheme = name
    ThemeEngine.currentRawTheme = theme

    Log.info("Applied theme:", name)
    ThemeEngine.notifySubscribers()
    return true
end

-- Get token value (Color3 or other)
function ThemeEngine.getToken(token)
    local v = ThemeEngine.tokens[token]
    if typeof(v) == "Color3" then return v end
    -- Defensive: a raw hex string that slipped through resolution -> Color3.
    if type(v) == "string" and v:sub(1, 1) == "#" then
        return hexToColor3(v)
    end
    return v
end

-- Get raw theme data
function ThemeEngine.getRawTheme(name)
    name = name or ThemeEngine.currentTheme
    return ThemeEngine.themes[name]
end

-- List available themes
function ThemeEngine.listThemes()
    local list = {}
    for name, theme in pairs(ThemeEngine.themes) do
        table.insert(list, {
            name = name,
            displayName = theme.name or name,
            author = theme.author,
            meta = theme.meta,
            extends = theme.extends
        })
    end
    return list
end

-- Subscribe to theme changes
function ThemeEngine.subscribe(callback)
    table.insert(ThemeEngine.subscribers, callback)
    return function()
        for i, cb in ipairs(ThemeEngine.subscribers) do
            if cb == callback then
                table.remove(ThemeEngine.subscribers, i)
                break
            end
        end
    end
end

function ThemeEngine.notifySubscribers()
    for _, cb in ipairs(ThemeEngine.subscribers) do
        pcall(cb, ThemeEngine.tokens, ThemeEngine.currentTheme)
    end
end

-- Hot-swap theme (called from UI)
function ThemeEngine.setTheme(name)
    local ok, err = ThemeEngine.applyTheme(name)
    if ok then
        -- Update config
        Config.set("theme.active", name)
        Config.save()
    else
        Log.error("Failed to apply theme:", err)
        -- Try fallback
        local fallback = Config.get("theme.fallback")
        if fallback and fallback ~= name then
            ThemeEngine.applyTheme(fallback)
        end
    end
    return ok, err
end

-- Start file watcher for themes directory
function ThemeEngine.startWatch(themesPath)
    if ThemeEngine.watchThread then return end
    ThemeEngine.watchThread = task.spawn(function()
        local lastFiles = {}
        while true do
            task.wait(2)
            local ok, files = Executor.fs_list(themesPath)
            if ok and files then
                local current = {}
                for _, f in ipairs(files) do
                    current[f] = true
                end
                -- Check for new/removed files
                local changed = false
                for f, _ in pairs(current) do
                    if not lastFiles[f] then
                        changed = true
                        local name = f:match("([^/\\]+)%.yaml$")
                        if name and not ThemeEngine.themes[name] then
                            local theme, err = ThemeEngine.loadTheme(name, themesPath)
                            if theme then
                                ThemeEngine.themes[name] = theme
                                Log.info("Hot-loaded new theme:", name)
                            end
                        end
                    end
                end
                for f, _ in pairs(lastFiles) do
                    if not current[f] then
                        changed = true
                        local name = f:match("([^/\\]+)%.yaml$")
                        if name and ThemeEngine.themes[name] then
                            ThemeEngine.themes[name] = nil
                            Log.info("Theme removed:", name)
                        end
                    end
                end
                if changed then
                    lastFiles = current
                    -- Notify UI to refresh theme list
                    ThemeEngine.notifySubscribers()
                end
            end
        end
    end)
end

function ThemeEngine.stopWatch()
    if ThemeEngine.watchThread then
        task.cancel(ThemeEngine.watchThread)
        ThemeEngine.watchThread = nil
    end
end

return ThemeEngine
end

TempleExModules["core"] = function()
--[[
    TempleEx Core Functions (Temple.Core)
    Declarative modules for built-in cheat functions
]]

local Core = {}
Core.__index = Core

local Executor = TempleExRequire("executor")
local Log = TempleExRequire("log")
local ThemeEngine = TempleExRequire("theme")
local Config = TempleExRequire("config")

Core.modules = {}       -- id -> module definition
Core.active = {}        -- id -> active state
Core.connections = {}   -- id -> {connection1, connection2, ...}
Core.flags = {}         -- id -> {param -> value}

-- Register a core function module
-- definition = {
--   id = "fly",
--   title = "Fly",
--   icon = "✈",  -- or image asset id
--   category = "Movement",
--   params = {
--     speed = { type = "number", default = 50, min = 1, max = 500, suffix = " studs/s" },
--     verticalSpeed = { type = "number", default = 50, min = 1, max = 500, suffix = " studs/s" }
--   },
--   keybind = "E",
--   onEnable = function(params) ... end,
--   onDisable = function() ... end,
--   onParamChange = function(param, value) ... end,
--   supportedExecutors = {"wave", "codex", ...}  -- nil = all
-- }
function Core.register(def)
    if not def.id then
        Log.error("Core.register: missing id")
        return
    end
    if Core.modules[def.id] then
        Log.warn("Core.register: overwriting module", def.id)
    end
    Core.modules[def.id] = def
    Core.active[def.id] = false
    Core.flags[def.id] = {}
    -- Initialize params with defaults
    if def.params then
        for k, v in pairs(def.params) do
            Core.flags[def.id][k] = v.default
        end
    end
    Log.debug("Registered core module:", def.id)
end

-- Get module definition
function Core.getModule(id)
    return Core.modules[id]
end

-- List all modules
function Core.listModules()
    local list = {}
    for id, def in pairs(Core.modules) do
        table.insert(list, {
            id = id,
            title = def.title,
            icon = def.icon,
            category = def.category,
            enabled = Core.active[id],
            params = Core.flags[id],
            keybind = def.keybind,
            supported = def.supportedExecutors == nil or table.find(def.supportedExecutors, Executor.info.name) ~= nil
        })
    end
    return list
end

-- Enable a module
function Core.enable(id)
    local def = Core.modules[id]
    if not def then
        return false, "Module not found: " .. id
    end

    -- Check executor support
    if def.supportedExecutors and table.find(def.supportedExecutors, Executor.info.name) == nil then
        return false, "Module '" .. id .. "' not supported on " .. Executor.info.name
    end

    if Core.active[id] then
        return true -- already enabled
    end

    -- Prepare params
    local params = Core.flags[id] or {}

    -- Call onEnable
    local ok, err = pcall(def.onEnable, params)
    if not ok then
        Log.error("Core enable error (" .. id .. "):", err)
        return false, err
    end

    Core.active[id] = true
    Log.info("Core module enabled:", id)

    -- Notify config to persist
    if Config and Config.set then
        Config.set("functions." .. id .. ".enabled", true)
        for k, v in pairs(params) do
            Config.set("functions." .. id .. "." .. k, v)
        end
        Config.save()
    end

    return true
end

-- Disable a module
function Core.disable(id)
    local def = Core.modules[id]
    if not def then
        return false, "Module not found: " .. id
    end

    if not Core.active[id] then
        return true -- already disabled
    end

    -- Call onDisable
    local ok, err = pcall(def.onDisable)
    if not ok then
        Log.error("Core disable error (" .. id .. "):", err)
        return false, err
    end

    Core.active[id] = false
    Log.info("Core module disabled:", id)

    if Config and Config.set then
        Config.set("functions." .. id .. ".enabled", false)
        Config.save()
    end

    return true
end

-- Toggle a module
function Core.toggle(id)
    if Core.active[id] then
        return Core.disable(id)
    else
        return Core.enable(id)
    end
end

-- Set parameter
function Core.setParam(id, param, value)
    local def = Core.modules[id]
    if not def then
        return false, "Module not found: " .. id
    end
    if not def.params or not def.params[param] then
        return false, "Parameter not found: " .. param
    end

    local pdef = def.params[param]
    -- Clamp/validate
    if pdef.type == "number" then
        value = tonumber(value) or pdef.default
        if pdef.min then value = math.max(pdef.min, value) end
        if pdef.max then value = math.min(pdef.max, value) end
    elseif pdef.type == "boolean" then
        value = value == true
    end

    Core.flags[id][param] = value

    if Core.active[id] and def.onParamChange then
        pcall(def.onParamChange, param, value)
    end

    if Config and Config.set then
        Config.set("functions." .. id .. "." .. param, value)
        Config.save()
    end

    return true
end

-- Get parameter
function Core.getParam(id, param)
    return Core.flags[id] and Core.flags[id][param]
end

-- Get all params for module
function Core.getParams(id)
    return Core.flags[id] or {}
end

-- Check if module is enabled
function Core.isEnabled(id)
    return Core.active[id] == true
end

-- Cleanup all modules (on unload/reload)
function Core.cleanupAll()
    for id, _ in pairs(Core.active) do
        if Core.active[id] then
            Core.disable(id)
        end
    end
end

-- Load persisted state from config
function Core.loadState(configData)
    if not configData or not configData.functions then return end
    for id, data in pairs(configData.functions) do
        if Core.modules[id] then
            if data.enabled then
                -- Restore params first
                for k, v in pairs(data) do
                    if k ~= "enabled" then
                        Core.flags[id][k] = v
                    end
                end
                -- Then enable
                task.spawn(function()
                    task.wait(0.1) -- small delay for other systems to initialize
                    Core.enable(id)
                end)
            end
        end
    end
end

return Core
end

