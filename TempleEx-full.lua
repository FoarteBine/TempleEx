        ResetOnSpawn = false,
        ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
        DisplayOrder = 100,
        IgnoreGuiInset = true
    })

    -- Parent to CoreGui (or gethui if available)
    local parent = Executor.gethui()
