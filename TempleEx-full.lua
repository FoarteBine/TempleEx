--[[
    TempleEx Logger
    Simple logging with levels, file output, and in-game console integration
]]

local Log = {}
Log.__index = Log

local Levels = {
    DEBUG = 1,
    INFO = 2,
    WARN = 3,
    ERROR = 4,
    FATAL = 5
}

local LevelNames = { "DEBUG", "INFO", "WARN", "ERROR", "FATAL" }

local currentLevel = Levels.INFO
local logFile = nil
local logBuffer = {}
local maxBuffer = 500

function Log.init(config)
