function TempleApi.Bind(options)
    options = options or {}
    local name = options.name
    local default = options.default
    local mode = options.mode or "toggle"
    local registry = options.registry or "global"
    local callback = options.callback

    local bind = {
        name = name,
        key = default,
        mode = mode,
        callback = callback,
        registry = registry
    }

    TempleApi._keybinds[name] = bind

    if default then
        local keyCode = default
        if type(default) == "string" then
            local okKey, kc = pcall(function() return Enum.KeyCode[default] end)
            keyCode = (okKey and kc) or nil
        end
        if keyCode then

        UserInputService.InputBegan:Connect(function(input, processed)
            if processed then return end
            if input.KeyCode == keyCode then
                if callback then pcall(callback, input) end
            end
        end)
        end
    end

    return bind
end

