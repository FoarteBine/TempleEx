        anchor = Vector2.new(0, 1)
        position = UDim2.new(0, 20, 1, -dockHeight - 20)
    else -- center
        anchor = Vector2.new(0.5, 0.5)
        position = UDim2.new(0.5, 0, 0.5, 0)
    end

